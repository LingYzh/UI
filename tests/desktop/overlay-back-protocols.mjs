import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createServer } from 'vite';
import { chromium } from 'playwright';

const evidence = path.resolve('artifacts/component-audit-root/overlay-back-protocols');
await mkdir(evidence, { recursive: true });
const files = ['UOverlay.vue', 'UiDialog.vue', 'UiMenu.vue', 'overlay-back.ts', 'overlay-lifecycle.ts', 'overlay-props.ts'];
const hashes = async () => Object.fromEntries(await Promise.all(files.map(async (file) => [file, createHash('sha256').update(await readFile(path.resolve('src/ui', file))).digest('hex')])));
const before = await hashes();
const fixture = `<!doctype html><html><head><meta charset="utf-8"><link rel="icon" href="data:,"></head><body><div id="app"></div><script type="module">
    import { createApp, h, nextTick, reactive, ref } from 'vue';
    import { createRouter, createWebHistory } from '/artifacts/full-alignment/vue-router/package/dist/vue-router.esm-browser.prod.js';
    import * as UI from '/src/ui/index.ts';
    import '/src/ui/styles.css';
    const router = createRouter({ history: createWebHistory('/__overlay_back__/'), routes: [{ path: '/:page', component: { render: () => null } }] });
    const state = reactive({ overlay: false, dialog: false, menu: false, persistent: false, enabled: true, mounted: true, overlayUpdates: 0, dialogUpdates: 0, menuUpdates: 0 });
    const menuRef = ref();
    const props = (key) => ({ modelValue: state[key], 'onUpdate:modelValue': value => { state[key] = value; state[key + 'Updates']++; }, closeOnBack: state.enabled, persistent: state.persistent });
    const app = createApp({ render: () => h('main', state.mounted ? [
        h(UI.UOverlay, { ...props('overlay'), contentProps: { id: 'back-overlay' } }, () => h('button', 'Overlay')),
        h(UI.UDialog, { ...props('dialog'), contentProps: { id: 'back-dialog' } }, { default: () => [h('button', { id: 'dialog-content' }, 'Dialog'), h(UI.UMenu, { ...props('menu'), ref: menuRef, contentProps: { id: 'back-menu' }, panel: true }, { default: () => h('button', 'Menu') })] })
    ] : []) });
    app.use(router).use(UI.createUI()).mount('#app');
    await router.isReady();
    window.backProbe = { state, router, read: () => ({ route: router.currentRoute.value.fullPath, ...state }), flush: async () => { await nextTick(); await nextTick(); }, app };
</script></body></html>`;
const vite = await createServer({ appType: 'custom', logLevel: 'error', cacheDir: path.join(evidence, 'vite-cache'), optimizeDeps: { noDiscovery: true, include: ['highlight.js/lib/core', 'highlight.js/lib/languages/xml', 'highlight.js/lib/languages/javascript', 'highlight.js/lib/languages/typescript', 'highlight.js/lib/languages/css', 'highlight.js/lib/languages/json', 'markdown-it', 'markdown-it-footnote', 'markdown-it-task-lists', 'markdown-it-deflist', 'markdown-it-mark', 'markdown-it-sub', 'markdown-it-sup'] }, server: { host: '127.0.0.1', port: 0, hmr: false } });
vite.middlewares.use('/__overlay_back__', async (_request, response) => { response.setHeader('Content-Type', 'text/html'); response.end(await vite.transformIndexHtml('/__overlay_back__', fixture)); });
const report = { generatedAt: new Date().toISOString(), routerVersion: '4.6.3', checks: [], errors: [], warnings: [], sourceSha256: before, visualAcceptance: false };
let browser;
try {
    await vite.listen();
    browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage();
    page.on('pageerror', error => report.errors.push(error.message));
    page.on('console', message => { if (message.type() === 'warning' && message.text().includes('[Vue warn]')) report.warnings.push(message.text()); });
    await page.goto(`http://127.0.0.1:${vite.httpServer.address().port}/__overlay_back__/one`);
    await page.waitForFunction(() => !!window.backProbe);
    const read = () => page.evaluate(() => window.backProbe.read());
    const set = async (values) => { await page.evaluate(async (values) => { Object.assign(window.backProbe.state, values); await window.backProbe.flush(); }, values); await page.waitForTimeout(220); };
    const push = async (route) => { await page.evaluate(route => window.backProbe.router.push(route), route); };
    const back = async () => { await page.evaluate(() => history.back()); await page.waitForTimeout(280); };
    await push('/two');
    await set({ overlay: true });
    await back();
    assert.equal((await read()).route, '/two');
    assert.equal((await read()).overlay, false);
    assert.equal(new URL(page.url()).pathname, '/__overlay_back__/two');
    report.checks.push('Back closes Overlay and Vue Router restores the current URL.');
    await back();
    assert.equal((await read()).route, '/one');
    report.checks.push('The next back navigates after the surface is closed.');
    await push('/two');
    await set({ dialog: true });
    await back();
    assert.equal((await read()).route, '/two');
    assert.equal((await read()).dialog, false);
    report.checks.push('Dialog uses the same default back protocol.');
    await set({ dialog: true });
    await set({ menu: true });
    await page.waitForFunction(() => document.querySelector('.ui-menu-surface')?.matches('[data-state=opening], [data-state=open], [data-state=closing]'));
    await back();
    assert.equal((await read()).route, '/two');
    assert.equal((await read()).menu, false);
    assert.equal((await read()).dialog, true);
    await back();
    assert.equal((await read()).dialog, false);
    report.checks.push('Nested Menu closes first; a second back closes its parent Dialog.');
    await set({ overlay: true, persistent: true });
    await back();
    assert.equal((await read()).route, '/two');
    assert.equal((await read()).overlay, true);
    assert.equal((await read()).overlayUpdates, 1);
    await back();
    assert.equal((await read()).route, '/two');
    report.checks.push('Persistent surfaces cancel repeated back without emitting a close.');
    await set({ persistent: false, enabled: false });
    await back();
    assert.equal((await read()).route, '/one');
    assert.equal((await read()).overlay, true);
    report.checks.push('closeOnBack=false lets routing proceed and keeps the surface open.');
    await set({ enabled: true });
    await push('/three');
    assert.equal((await read()).route, '/three');
    assert.equal((await read()).overlay, true);
    report.checks.push('Programmatic navigation is not mistaken for a history pop.');
    await set({ mounted: false });
    await back();
    assert.equal((await read()).route, '/one');
    report.checks.push('Unmount removes guards and stack registrations.');
    assert.deepEqual(report.errors, []);
    assert.deepEqual(report.warnings, []);
    assert.deepEqual(await hashes(), before);
    report.sourceStable = true;
    await writeFile(path.join(evidence, 'report.json'), JSON.stringify(report, null, 4));
    process.stdout.write(`overlay back protocols: ${report.checks.length} checks passed\n`);
} finally {
    await browser?.close();
    await vite.close();
}
