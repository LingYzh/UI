import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';
import { createServer } from 'vite';

const evidence = path.resolve('artifacts/component-audit-root/alignment-visual-remaining');
await mkdir(evidence, { recursive: true });
const sources = ['src/ui/UOtpInput.vue', 'src/ui/UNumberInput.vue', 'src/ui/USlider.vue', 'src/ui/URangeSlider.vue', 'src/ui/UColorPicker.vue', 'src/ui/UColorInput.vue', 'src/ui/USkeletonLoader.vue', 'src/ui/UiDialog.vue', 'src/ui/UiContainer.vue', 'src/ui/UMain.vue', 'src/ui/UiRow.vue', 'src/ui/UiThemeProvider.vue', 'src/ui/forms-components.css', 'src/ui/styles.css', 'src/ui/layout-components.css'];
const hashes = async () => Object.fromEntries(await Promise.all(sources.map(async file => [file, createHash('sha256').update(await readFile(file)).digest('hex')])));
sources.push(...['otp-input', 'number-input', 'slider', 'range-slider', 'skeleton-loader', 'color-picker'].map(name => `src/ui/docs/component-examples/${name}.vue`), 'src/ui/docs/DialogGeometryDemo.vue', 'src/ui/docs/LayoutBasicsDemo.vue');
const before = await hashes();
const fixture = `<!doctype html><html><head><meta charset="utf-8"><link rel="icon" href="data:,"><style>html,body,#app{height:auto!important;overflow:visible!important}body{margin:0;padding:20px;background:var(--background);color:var(--text)}main{display:grid;grid-template-columns:repeat(2,minmax(0,1fr));gap:20px;max-width:1100px;margin:auto}section.preview{min-width:0;padding:18px;border:1px solid var(--border);border-radius:12px;background:var(--surface)}h2{font-size:18px;margin:0 0 20px}@media(max-width:650px){body{padding:14px}main{grid-template-columns:minmax(0,1fr)}}.preview .demo-row{display:flex;gap:12px;flex-wrap:wrap}</style></head><body><div id="app"></div><script type="module">
import {createApp,h} from 'vue';import {createUI} from '/src/ui/index.ts';import '/src/docs-base.css';import '/src/ui/styles.css';
import OTP from '/src/ui/docs/component-examples/otp-input.vue';
import NumberInput from '/src/ui/docs/component-examples/number-input.vue';
import Slider from '/src/ui/docs/component-examples/slider.vue';
import RangeSlider from '/src/ui/docs/component-examples/range-slider.vue';
import Skeleton from '/src/ui/docs/component-examples/skeleton-loader.vue';
import ColorPicker from '/src/ui/docs/component-examples/color-picker.vue';
import Dialog from '/src/ui/docs/DialogGeometryDemo.vue';
import Layout from '/src/ui/docs/LayoutBasicsDemo.vue';
const demos=[['otp','OTP',OTP],['number','NumberInput',NumberInput],['slider','Slider',Slider],['range','RangeSlider',RangeSlider],['skeleton','SkeletonLoader',Skeleton],['color','ColorPicker',ColorPicker],['dialog','Dialog',Dialog],['layout','Layout',Layout]];
const ui=createUI();createApp({render:()=>h('main',{},demos.map(([id,title,component])=>h('section',{id,class:'preview'},[h('h2',title),h(component)])))}).use(ui).mount('#app');window.visualReady={theme:value=>ui.theme.change(value,false)};
</script></body></html>`;
const server = await createServer({ appType: 'custom', cacheDir: path.join(evidence, 'cache'), server: { host: '127.0.0.1', port: 0 }, logLevel: 'error', optimizeDeps: { noDiscovery: true, include: ['highlight.js/lib/core', 'highlight.js/lib/languages/xml', 'highlight.js/lib/languages/javascript', 'highlight.js/lib/languages/typescript', 'highlight.js/lib/languages/css', 'highlight.js/lib/languages/json', 'markdown-it', 'markdown-it-footnote', 'markdown-it-task-lists', 'markdown-it-deflist', 'markdown-it-mark', 'markdown-it-sub', 'markdown-it-sup'] } });
server.middlewares.use('/__remaining_visual__', async (_request, response) => {
    response.setHeader('Content-Type', 'text/html');
    response.end(await server.transformIndexHtml('/__remaining_visual__', fixture));
});
let browser;
const checks = [];
const errors = [], warnings = [];
try {
    await server.listen();
    browser = await chromium.launch({ headless: true });
    const page = await browser.newPage({ viewport: { width: 1200, height: 1000 } });
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'warning') warnings.push(message.text()); if (message.type() === 'error') errors.push(message.text()); });
    await page.goto('http://127.0.0.1:' + server.httpServer.address().port + '/__remaining_visual__');
    await page.waitForFunction(() => !!window.visualReady);
    const otp = page.locator('#otp .ui-otp-input input').first();
    const shadow = () => otp.evaluate(node => getComputedStyle(node).boxShadow);
    await otp.evaluate(node => node.blur());
    await page.waitForTimeout(180);
    const idle = await shadow();
    await otp.focus();
    await page.waitForTimeout(40);
    const entering = await shadow();
    await page.waitForTimeout(160);
    const focused = await shadow();
    await page.locator('#otp').screenshot({ path: path.join(evidence, 'otp-focused.png') });
    assert.notEqual(entering, idle);
    assert.notEqual(entering, focused, 'focus ring has an actual intermediate fade-in state');
    await otp.evaluate(node => node.blur());
    await page.waitForTimeout(40);
    const leaving = await shadow();
    await page.waitForTimeout(160);
    assert.notEqual(leaving, focused);
    assert.notEqual(leaving, await shadow(), 'focus ring has an actual intermediate fade-out state');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await otp.evaluate(node => getComputedStyle(node).transitionDuration), '0s');
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    checks.push('real OTP demo fade-in/fade-out intermediate states and reduced-motion');
    const range = page.locator('#range .ui-range-slider-track').first();
    assert.equal(await range.locator('input').first().getAttribute('max'), '100');
    assert.equal(await range.locator('input').last().getAttribute('min'), '0');
    const vertical = page.locator('#slider .is-vertical input').first();
    assert.equal(await vertical.evaluate(node => getComputedStyle(node).writingMode), 'vertical-lr');
    assert.equal(await vertical.evaluate(node => getComputedStyle(node).direction), 'rtl');
    assert.equal(await page.locator('#slider .is-vertical.is-reversed input').evaluate(node => getComputedStyle(node).direction), 'ltr');
    checks.push('native range thumbs share full model axis and vertical/reverse styles are consumed');
    await page.locator('#skeleton button').click();
    assert.equal(await page.locator('#skeleton .ui-skeleton-loader').count(), 3);
    await page.locator('#skeleton button').click();
    assert.equal(await page.locator('#skeleton .ui-card').count(), 1);
    checks.push('real Skeleton demo toggles content and loading');
    await page.locator('#dialog button').first().click();
    await page.waitForFunction(() => document.querySelector('dialog[open]')?.dataset.state === 'open');
    assert.equal(Math.round((await page.locator('dialog[open]').boundingBox()).width), 420);
    await page.screenshot({ path: path.join(evidence, 'dialog-light-wide.png') });
    await page.getByRole('button', { name: '关闭', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('dialog[open]'));
    for (const [theme, width, zoom] of [['light', 1200, '100%'], ['dark', 390, '100%'], ['light', 390, '125%']]) {
        await page.evaluate(theme => window.visualReady.theme(theme), theme);
        await page.setViewportSize({ width, height: 1000 });
        await page.evaluate(zoom => { document.body.style.zoom = zoom; }, zoom);
        await page.waitForTimeout(180);
        await page.screenshot({ path: path.join(evidence, `${theme}-${width}-${zoom}.png`), fullPage: true });
        if (theme === 'dark') await page.locator('#color').screenshot({ path: path.join(evidence, 'color-dark-narrow.png') });
        const overflow = await page.evaluate(() => ({ width: document.documentElement.scrollWidth, viewport: innerWidth, nodes: [...document.querySelectorAll('body *')].filter(node => node.getBoundingClientRect().right > innerWidth + 1).slice(0, 15).map(node => ({ tag: node.tagName, class: node.className, text: node.textContent.slice(0, 60), bounds: { width: node.getBoundingClientRect().width, right: node.getBoundingClientRect().right } })) }));
        assert.ok(overflow.width <= overflow.viewport, `${theme}/${width}/${zoom} page has no horizontal overflow: ${JSON.stringify(overflow)}`);
    }
    checks.push('real demos light/dark/narrow/125% zoom without page overflow');
    assert.deepEqual(errors, []);
    assert.deepEqual(warnings, []);
    assert.deepEqual(await hashes(), before);
    await writeFile(path.join(evidence, 'report.json'), JSON.stringify({ checks, sourceHashes: before, errors, warnings, visualAcceptance: false }, null, 4));
    process.stdout.write(JSON.stringify({ checks: checks.length, evidence }));
} finally {
    await browser?.close();
    await server.close();
}
