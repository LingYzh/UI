import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import path from 'node:path';

test('every public component is included in the global registration table', () => {
    const entry = readFileSync('src/ui/index.ts', 'utf8');
    const registry = readFileSync('src/ui/component-registry.ts', 'utf8');
    const names = [...entry.matchAll(/export\s*\{\s*default\s+as\s+(U[A-Z]\w*)\s*\}/g)].map(match => match[1]);
    const registered = registry.split('export const components = {')[1].split('};')[0];
    assert.ok(names.length >= 160);
    for (const name of names) assert.match(registered, new RegExp(`\\b${name},`), name);
});

test('registry generation preserves public aliases, functions and types and is repeatable', (context) => {
    const directory = mkdtempSync(path.join(tmpdir(), 'ui-registration-'));
    context.after(() => rmSync(directory, { recursive: true, force: true }));
    mkdirSync(path.join(directory, 'src/ui'), { recursive: true });
    mkdirSync(path.join(directory, 'artifacts'));
    const entryPath = path.join(directory, 'src/ui/index.ts');
    const original = `export { default as UiField } from './UiField.vue';

// Canonical u- component exports (generated by scripts/sync-components.mjs).
export { default as UFormField } from './UiField.vue';
export { default as UField } from './UField.vue';
export type { ImportantContract } from './contracts';
export { publicHelper } from './helper';
`;
    writeFileSync(entryPath, original);
    for (const filename of ['UiField.vue', 'UField.vue', 'UTreeTable.vue']) {
        writeFileSync(path.join(directory, 'src/ui', filename), '<template><div /></template>');
    }
    const generator = path.resolve('scripts/sync-components.mjs');
    execFileSync(process.execPath, [generator], { cwd: directory });
    const generated = readFileSync(entryPath, 'utf8');
    assert.ok(generated.startsWith(original));
    assert.match(generated, /default as UTreeTable/);
    const registryPath = path.join(directory, 'src/ui/component-registry.ts');
    const registry = readFileSync(registryPath, 'utf8');
    assert.match(registry, /import UFormField from '.\/UiField.vue'/);
    assert.match(registry, /import UField from '.\/UField.vue'/);
    assert.match(registry, /UTreeTable,/);
    execFileSync(process.execPath, [generator], { cwd: directory });
    assert.equal(readFileSync(entryPath, 'utf8'), generated);
    assert.equal(readFileSync(registryPath, 'utf8'), registry);
});
