import { writeFile } from 'node:fs/promises';
import { typography } from '../src/ui/typography.js';

const aliases = { caption: 'body-small', 'body-1': 'body-large', 'body-2': 'body-medium', subtitle: 'title-medium', title: 'title-large' };
function rule(name, role) {
    return `.text-${name} { font-size: var(--ui-font-${role.name}) !important; line-height: ${role.lineHeight / 16}rem !important; font-weight: ${role.weight} !important; }`;
}
const tokens = typography.map(role => `    --ui-font-${role.name}: ${role.size / 16}rem;`).join('\n');
const classes = typography.map(role => rule(role.name, role)).join('\n');
const legacy = Object.entries(aliases).map(([name, target]) => rule(name, typography.find(role => role.name === target))).join('\n');
const responsive = Object.entries({ sm: 600, md: 960, lg: 1280, xl: 1920, xxl: 2560 }).map(([prefix, width]) => `@media (min-width: ${width}px) {\n${typography.map(role => '    ' + rule(`${prefix}-${role.name}`, role)).join('\n')}\n}`).join('\n');
await writeFile(new URL('../src/ui/typography.css', import.meta.url), `/* Generated by scripts/sync-typography.mjs; Vuetify 4.2.4 type scale. */\n:root {\n${tokens}\n}\n${classes}\n${legacy}\n${responsive}\n`);
