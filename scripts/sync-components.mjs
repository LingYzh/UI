import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const file = 'src/ui/index.ts';
const marker = '// Canonical u- component exports (generated by scripts/sync-components.mjs).';
const source = readFileSync(file, 'utf8');
const original = source.split(marker)[0].trimEnd();
// 保留人工补充的公开别名、工具和类型；不能按文件名重建时丢掉 UFormField 等契约。
const canonical = source.split(marker)[1]?.trim() ?? '';
const existing = [...canonical.matchAll(/export\s*\{\s*default\s+as\s+(U[A-Z]\w*)\s*\}\s*from\s*['"]([^'"]+\.vue)['"]/g)].map(match => ({ name: match[1], file: match[2] }));
const legacy = [...original.matchAll(/export\s*\{\s*default\s+as\s+(Ui\w+)\s*\}\s*from\s*['"]([^'"]+\.vue)['"]/g)].map(match => ({ legacy: match[1], name: match[1] === 'UiInput' ? 'UTextField' : match[1] === 'UiBadge' ? 'UChip' : match[1].replace(/^Ui/, 'U'), file: match[2] }));
const components = new Map(existing.map(entry => [entry.name, entry]));
for (const entry of legacy) if (!components.has(entry.name)) components.set(entry.name, entry);
for (const name of readdirSync('src/ui').filter(name => /^U(?!i)[A-Z].*\.vue$/.test(name)).sort()) {
    const key = name.slice(0, -4);
    if (!components.has(key)) components.set(key, { name: key, file: `./${name}` });
}
const rows = [...components.values()];
const existingNames = new Set(existing.map(entry => entry.name));
const additions = rows.filter(entry => !existingNames.has(entry.name)).map(entry => `export { default as ${entry.name} } from '${entry.file}';`).join('\n');
writeFileSync(file, `${original}\n\n${marker}\n${[canonical, additions].filter(Boolean).join('\n')}\n`);
const imports = rows.map(entry => `import ${entry.name} from '${entry.file}';`).join('\n');
const legacyImports = legacy.map(entry => `import Legacy${entry.legacy} from '${entry.file}';`).join('\n');
writeFileSync('src/ui/component-registry.ts', `// Generated component registry. Named imports remain available from index.ts.\n${imports}\n${legacyImports}\n\nexport const components = {\n${rows.map(entry => `    ${entry.name},`).join('\n')}\n};\nexport const legacyComponents = {\n${legacy.map(entry => `    ${entry.legacy}: Legacy${entry.legacy},`).join('\n')}\n};\n`);
writeFileSync('artifacts/component-catalog.json', `${JSON.stringify(rows.map(entry => ({ ...entry, source: path.posix.normalize(`src/ui/${entry.file}`) })), null, 4)}\n`);
console.log(`Canonical components: ${rows.length}. Legacy aliases: ${legacy.length}.`);
